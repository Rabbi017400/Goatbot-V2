"use strict";

const fs = require("fs");
const path = require("path");

const spec = require("./tables-spec.json");
const outFile = process.argv[2] || path.join(__dirname, "..", "src", "lightspeed", "decoders.js");

const numericTypes = new Set([
  "int", "int32", "int8", "int16", "uint32", "float64", "float32",
  "Gender", "ContactIDType", "ContactViewerRelationship", "ThreadSourceType", "AttachmentType",
  "SendType", "InitiatingSource", "MessageUnsendabilityStatus", "AppState", "ReactionStyle",
  "RestrictionType", "SearchType", "ThreadType", "FolderType", "ThreadBumpStatus",
  "ReplySourceTypeV2", "EphemeralMediaViewMode", "EphemeralMediaState", "DisplayedContentTypes",
  "StringOrInt",
]);
const int64Types = new Set(["int64", "uint64"]);
const boolTypes = new Set(["bool"]);
const stringTypes = new Set(["string"]);

const structNames = Object.keys(spec.structs).sort();
const out = [];
out.push('"use strict";');
out.push("");
out.push("// GENERATED by tools/gen-decoders.js from tools/tables-spec.json.");
out.push("// Do not edit by hand; re-run `node tools/gen-decoders.js` after updating tools/tables-spec.json.");
out.push("");
out.push('const { int, bigint, str, bool, any } = require("./values");');
out.push("");

for (const name of structNames) {
  const struct = spec.structs[name];
  const indexByName = {};
  for (const f of struct.fields) if (f.index !== undefined) indexByName[f.name] = f.index;

  out.push(`function decode${name}(data, ls) {`);
  out.push("  const out = {};");
  const declared = new Map();
  const fields = struct.fields.filter((f) => f.index !== undefined || f.conditionField);
  for (const field of fields) {
    let varName;
    let expr;
    if (field.conditionField) {
      varName = "i_" + field.name;
      const condIndex = indexByName[field.conditionField];
      const [trueIdx, falseIdx] = field.indexes.split(",");
      const condExpr = condIndex === undefined ? "false" : `bool(data[${condIndex}])`;
      expr = `(${condExpr} ? ${trueIdx} : ${falseIdx})`;
    } else {
      varName = "i" + field.index;
      expr = String(field.index);
    }
    if (!declared.has(varName)) {
      out.push(`  const ${varName} = ${expr};`);
      declared.set(varName, true);
    }
    field._var = varName;
  }
  const usedIndexes = new Set();
  for (const field of fields) {
    const type = field.goType;
    let coerce;
    if (int64Types.has(type)) coerce = "bigint";
    else if (numericTypes.has(type)) coerce = "int";
    else if (boolTypes.has(type)) coerce = "bool";
    else if (stringTypes.has(type)) coerce = "str";
    else coerce = "any";
    const v = field._var;
    out.push(`  if (${v} < data.length && data[${v}] !== undefined && data[${v}] !== null) out.${field.name} = ${coerce}(data[${v}]);`);
    if (field.index !== undefined) usedIndexes.add(field.index);
    if (field.conditionField) {
      for (const raw of field.indexes.split(",")) usedIndexes.add(parseInt(raw, 10));
    }
  }
  if (struct.fields.some((f) => f.name === "Unrecognized")) {
    out.push("  const used = new Set([" + [...usedIndexes].sort((a, b) => a - b).join(", ") + "]);");
    out.push("  for (let i = 0; i < data.length; i++) {");
    out.push("    if (!used.has(i) && data[i] !== undefined && data[i] !== null) {");
    out.push("      if (!out.Unrecognized) out.Unrecognized = {};");
    out.push("      out.Unrecognized[i] = any(data[i]);");
    out.push("    }");
    out.push("  }");
  }
  out.push("  return out;");
  out.push("}");
  out.push("");
}

out.push("const DECODERS = {");
for (const name of structNames) out.push(`  ${name}: decode${name},`);
out.push("};");
out.push("");

const aliases = {};
const lsTable = spec.structs.LSTable;
if (lsTable) {
  for (const field of lsTable.fields) {
    const m = /^\[\]\*(.+)$/.exec(field.goType || "");
    if (m && m[1] !== field.name && structNames.includes(m[1])) aliases[field.name] = m[1];
  }
}
out.push("const DECODER_ALIASES = {");
for (const key of Object.keys(aliases).sort()) out.push(`  ${key}: ${JSON.stringify(aliases[key])},`);
out.push("};");
out.push("");
out.push("module.exports = { DECODERS, DECODER_ALIASES };");
out.push("");

fs.writeFileSync(outFile, out.join("\n"));
console.log("Wrote", outFile, "with", structNames.length, "decoders");
